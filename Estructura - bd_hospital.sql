-- 9. ASIGNACIONES DE CAMAS

CREATE TABLE ti_asignaciones_camas (
    id_asignacion BIGSERIAL PRIMARY KEY,
    id_internacion BIGINT NOT NULL,
    id_cama BIGINT NOT NULL,
    fecha_ingreso TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_salida TIMESTAMP,
    observaciones_asignacion TEXT,

    CONSTRAINT fk_asignacion_internacion
        FOREIGN KEY (id_internacion)
        REFERENCES ti_internaciones(id_internacion),

    CONSTRAINT fk_asignacion_cama
        FOREIGN KEY (id_cama)
        REFERENCES ti_camas(id_cama),

    CONSTRAINT chk_fechas_asignacion
        CHECK (
            fecha_salida IS NULL
            OR fecha_salida >= fecha_ingreso
        )
);


