-- ===== TABLAS CATÁLOGO =====

CREATE TABLE tp_turnos (
    id_turno SERIAL PRIMARY KEY,
    nombre_turno VARCHAR(30) NOT NULL UNIQUE,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    activo BOOLEAN DEFAULT TRUE
);

CREATE TABLE tp_especialidades (
    id_especialidad SERIAL PRIMARY KEY,
    nombre_especialidad VARCHAR(80) NOT NULL UNIQUE,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('Medica', 'Enfermeria', 'Apoyo', 'Administrativa')),
    descripcion TEXT,
    activo BOOLEAN DEFAULT TRUE
);

CREATE TABLE tp_areas (
    id_area SERIAL PRIMARY KEY,
    nombre_area VARCHAR(80) NOT NULL UNIQUE,
    descripcion TEXT,
    activo BOOLEAN DEFAULT TRUE
);

-- ===== TABLAS PRINCIPALES =====

CREATE TABLE tp_personas (
    id_persona SERIAL PRIMARY KEY,
    ci VARCHAR(20) NOT NULL UNIQUE,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    genero CHAR(1) NOT NULL CHECK (genero IN ('M', 'F', 'O')),
    telefono VARCHAR(20),
    email VARCHAR(100),
    direccion TEXT,
    foto_url VARCHAR(255),
    fecha_creacion TIMESTAMP DEFAULT NOW(),
    activo BOOLEAN DEFAULT TRUE
);

CREATE TABLE tp_pacientes (
    id_paciente SERIAL PRIMARY KEY,
    id_persona INTEGER NOT NULL UNIQUE REFERENCES tp_personas(id_persona),
    aseguradora_nombre VARCHAR(100),
    aseguradora_codigo VARCHAR(20),
    aseguradora_empresa VARCHAR(100),
    numero_poliza VARCHAR(50),
    tipo_afiliacion VARCHAR(20) NOT NULL CHECK (tipo_afiliacion IN ('Particular', 'Asegurado')),
    contacto_emergencia_nombre VARCHAR(100),
    contacto_emergencia_telefono VARCHAR(20),
    alergias_conocidas TEXT,
    observaciones TEXT,
    fecha_registro TIMESTAMP DEFAULT NOW(),
    activo BOOLEAN DEFAULT TRUE
);

CREATE TABLE tp_empleados (
    id_empleado SERIAL PRIMARY KEY,
    id_persona INTEGER NOT NULL UNIQUE REFERENCES tp_personas(id_persona),
    id_area INTEGER REFERENCES tp_areas(id_area),
    tipo_empleado VARCHAR(20) NOT NULL CHECK (tipo_empleado IN ('Medico', 'Enfermero', 'Administrativo', 'Auxiliar', 'Otro')),
    fecha_contratacion DATE NOT NULL,
    fecha_terminacion DATE,
    id_turno INTEGER NOT NULL,-- REFERENCES tp_turnos(id_turno),
    sueldo_base DECIMAL(10,2),
    activo BOOLEAN DEFAULT TRUE
);

-- ===== TABLA DE RELACIÓN PERSONAL-ESPECIALIDADES (N:M) =====

CREATE TABLE tp_empleado_especialidades (
    id_relacion SERIAL PRIMARY KEY,
    id_empleado INTEGER NOT NULL REFERENCES tp_empleados(id_empleado),
    id_especialidad INTEGER NOT NULL REFERENCES tp_especialidades(id_especialidad),
    fecha_asignacion DATE DEFAULT NOW(),
    observaciones TEXT,
    UNIQUE(id_empleado, id_especialidad)
);

