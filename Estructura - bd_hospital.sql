-- 4. Tabla SC_FACTURA
CREATE TABLE td_FACTURA (
    id_factura integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente INT NOT NULL,
    id_usuario INT NOT NULL,
    nro_factura VARCHAR(50) NOT NULL UNIQUE,
    nit_cliente VARCHAR(20) NOT NULL,
    razon_social VARCHAR(150) NOT NULL,
    fecha_emision DATE DEFAULT CURRENT_TIMESTAMP,
    monto_total DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    metodo_pago VARCHAR(50) NOT NULL,

    FOREIGN KEY (id_usuario)
        REFERENCES ts_usuarios(id_usuario),

    CONSTRAINT chk_monto_total
        CHECK (monto_total >= 0),

    CONSTRAINT chk_metodo_pago
        CHECK (
            metodo_pago IN (
                'EFECTIVO',
                'TARJETA',
                'TRANSFERENCIA',
                'SEGURO'
            )
        )
);


-- 5. Tabla SC_SERVICIOS
CREATE TABLE td_SERVICIOS (
    id_servicio integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_servicio VARCHAR(50) NOT NULL UNIQUE,
    nombre_servicio VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    tipo_servicio VARCHAR(50),
    precio_base DECIMAL(10, 2) NOT NULL,

    CONSTRAINT chk_precio_base
        CHECK (precio_base >= 0)
);


-- 6. Tabla SC_DETALLE_FACTURA
CREATE TABLE td_DETALLE_FACTURA (
    id_detalle integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_factura INT NOT NULL,
    id_servicio INT NOT NULL,
    cantidad INT NOT NULL DEFAULT 1,
    precio_unitario DECIMAL(10, 2) NOT NULL,
    subtotal DECIMAL(10, 2) NOT NULL,

    FOREIGN KEY (id_factura)
        REFERENCES td_FACTURA(id_factura)
        ON DELETE CASCADE,

    FOREIGN KEY (id_servicio)
        REFERENCES td_SERVICIOS(id_servicio),

    CONSTRAINT chk_cantidades_detalle
        CHECK (
            cantidad > 0
            AND precio_unitario >= 0
            AND subtotal >= 0
        )
);

