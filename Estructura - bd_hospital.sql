-- Fichas del dia con datos legibles (paciente, medico, servicio, estado) --
CREATE VIEW public.v_fichas_dia AS
 SELECT f.id_ficha,
        f.nro_ficha,
        f.id_persona,
        f.ci_paciente,
        f.tipo_paciente,
        CASE f.tipo_paciente
            WHEN 'A'::bpchar THEN 'Asegurado'::text
            ELSE 'Particular'::text
        END AS tipo_desc,
        CASE WHEN a.ci IS NOT NULL
             THEN ((a.nombre::text || ' ') || a.paterno::text) || ' ' || a.materno::text
             ELSE f.ci_paciente::text
        END AS paciente,
        e.nombre_especialidad AS especialidad,
        --(((mp.nombre::text || ' ') || mp.apellidos::text)) AS medico,
        s.nombre_servicio AS servicio,
        f.fech_cita,
        f.hora_cita,
        f.estado,
        CASE f.estado
            WHEN 'R'::bpchar THEN 'Registrada'::text
            WHEN 'C'::bpchar THEN 'Confirmada'::text
            WHEN 'A'::bpchar THEN 'Atendida'::text
            WHEN 'N'::bpchar THEN 'No asistio'::text
            WHEN 'X'::bpchar THEN 'Cancelada'::text
            ELSE NULL::text
        END AS estado_desc,
        f.observacion,
        f.fech_reg,
        f.usuario_reg
   FROM tc_ficha f
     JOIN tp_especialidades e ON e.id_especialidad = f.id_especialidad
     JOIN tp_empleados em ON em.id_empleado = f.id_medico
     JOIN tp_personas mp ON mp.id_persona = em.id_persona
     LEFT JOIN tc_servicios s ON s.id_servicio = f.id_servicio
     LEFT JOIN tp_asegurado a ON a.ci::text = f.id_asegurado::text;

