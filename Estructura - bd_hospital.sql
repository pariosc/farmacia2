CREATE TABLE ti_camas (
    id_cama BIGSERIAL PRIMARY KEY,
    id_habitacion BIGINT NOT NULL,
    estado_cama VARCHAR(30) NOT NULL DEFAULT 'DISPONIBLEti_',

    CONSTRAINT fk_cama_habitacion
        FOREIGN KEY (id_habitacion)
        REFERENCES ti_habitaciones(id_habitacion),

