-- 1. Tabla de Rolees
CREATE TABLE ts_roles (
    id_rol integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol VARCHAR(50) NOT NULL UNIQUE,
    descripcion VARCHAR(255),
    estado_rol BOOLEAN DEFAULT TRUE
);

-- 2. Tabla de Usuarios
CREATE TABLE ts_usuarios (
    id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_personal INT NOT NULL UNIQUE,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    estado_cuenta VARCHAR(20) DEFAULT 'ACTIVO',

    CONSTRAINT chk_estado_cuenta
        CHECK (estado_cuenta IN ('ACTIVO', 'INACTIVO', 'BLOQUEADO'))
);

-- 3. Tabla Intermedia Roles_Usuarios
CREATE TABLE ts_roles_usuarios (
    id_usuario INT NOT NULL,
    id_rol INT NOT NULL,
    fecha_asignacion DATE DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id_usuario, id_rol),

    FOREIGN KEY (id_usuario)
        REFERENCES ts_usuarios(id_usuario)
        ON DELETE CASCADE,

    FOREIGN KEY (id_rol)
        REFERENCES ts_roles(id_rol)
        ON DELETE CASCADE
);


