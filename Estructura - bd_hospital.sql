    id_internacion BIGSERIAL PRIMARY KEY,
    id_medico BIGINT NOT NULL,
    id_paciente BIGINT NOT NULL,
    id_tipo_internacion BIGINT NOT NULL,
    fecha_internacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observaciones_internacion TEXT,

    CONSTRAINT fk_internacion_doctor
        FOREIGN KEY (id_medico)
        REFERENCES tp_personas(id_persona),

    CONSTRAINT fk_internacion_paciente
        FOREIGN KEY (id_paciente)
        REFERENCES tp_personas(id_persona),

    CONSTRAINT fk_internacion_tipo
        FOREIGN KEY (id_tipo_internacion)
        REFERENCES ti_tipos_internaciones(id_tipo_internacion)
